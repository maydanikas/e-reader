const dictionaries: Record<Locale, Record<MsgKey, string>> = { ru, en, nl, de, es, fr };

export function detectLocale(): Locale {
  const lang = ((navigator.languages && navigator.languages[0]) || navigator.language || 'en').toLowerCase();
  if (lang.startsWith('nl')) return 'nl';
  if (lang.startsWith('de')) return 'de';
  if (lang.startsWith('es')) return 'es';
  if (lang.startsWith('fr')) return 'fr';
  if (lang.startsWith('ru') || lang.startsWith('uk') || lang.startsWith('be')) return 'ru';
  return 'en';
}

export function formatMsg(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, key: string) => (
    vars[key] == null ? `{${key}}` : String(vars[key])
  ));
}

export function translate(locale: Locale, key: MsgKey, vars?: Record<string, string | number>): string {
  return formatMsg(dictionaries[locale][key] || dictionaries.en[key], vars);
}
